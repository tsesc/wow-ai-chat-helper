-- ns.L.KEY: the string for the active language (ns.lang), zhTW when that language
-- lacks it, the key itself as a last resort (never nil, so concatenation can't fail).
ns.L = setmetatable({}, {
	__index = function(_, k)
		local t = Locales[ns.lang or "zhTW"] or Locales.zhTW
		local v = t[k]
		if v == nil then v = Locales.zhTW[k] end
		if v == nil then v = tostring(k) end
		return v
	end,
})

-- ns.F("KEY", ...) = string.format(L.KEY, ...)
function ns.F(key, ...)
	local ok, s = pcall(string.format, ns.L[key], ...)
	if ok then return s end
	return ns.L[key]
end
